# ``.. code-block:: tree``: directory trees whose ``# comments`` are set off from the
# file names (docs/outputs.rst; generated by scripts/dev/docs/make_output_tree.py).
from pygments.lexer import RegexLexer  # noqa: E402
from pygments.token import Comment, Punctuation, Text  # noqa: E402


class TreeLexer(RegexLexer):
    name = "tree"
    tokens = {
        "root": [
            (r"#.*$", Comment),
            (r"[│├└─]+", Punctuation),
            (r"[^#│├└─\n]+", Text),
            (r"\n", Text),
        ]
    }


def setup(app):
    app.add_lexer("tree", TreeLexer)
