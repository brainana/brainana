#!/usr/bin/env python3
"""Write a training YAML from a checkpoint's embedded config plus a training recipe.

The network (MODEL.*) and preprocessing (DATA.PREPROCESSING, PLANE, SIZES, PADDED_SIZE,
CLASS_OPTIONS) are copied EXACTLY from the checkpoint, so a fine-tuned model sees data
prepared the same way as the model it starts from and as inference will prepare it. The
training recipe (optimizer, schedule, augmentation, loader, early stopping) comes from the
recipe below and --set overrides. Keys the trainer ignores are not written.

    python -m fastsurfer_nn.scripts.make_training_yaml \
        --from-checkpoint src/fastsurfer_nn/pretrained_model/T1w_seg-ARM2_coronal.pkl \
        --contrast T2w --data-dir .../training_data/T2w_seg-ARM2 \
        --output-dir .../training_output/T2w_seg-ARM2_coronal_lia_v1 \
        --out src/fastsurfer_nn/config/T2w_ARM2_coronal_lia.yaml \
        --set OPTIMIZER.BASE_LR=0.001
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import yaml

_src = Path(__file__).resolve().parents[2]
if str(_src) not in sys.path:
    sys.path.insert(0, str(_src))

from fastsurfer_nn.utils.checkpoint import read_checkpoint_file  # noqa: E402

# Fine-tuning recipe (2026-11). Rationale in docs_temp/t2w_segmentation_training.md.
RECIPE = {
    "TRAIN": {
        "BATCH_SIZE": 16,
        "ACCUM_STEPS": 1,
        "NUM_EPOCHS": 60,
        "LOG_INTERVAL": 50,
        "CHECKPOINT_PERIOD": 1,
        "FINE_TUNE": True,
        "RESUME": False,
        "SELECTION_METRIC": "val_dice",
        "EARLY_STOPPING": True,
        "EARLY_STOPPING_PATIENCE": 10,
        "EARLY_STOPPING_WAIT": 5,
        "EARLY_STOPPING_DELTA": 0.0005,
        "AMP": "bf16",
        "CHANNELS_LAST": False,
        "COMPILE": False,
        "DETERMINISTIC": False,
        "SNAPSHOT_SLICES": 4,
        "MONITOR": True,
        "NUM_WORKERS": 3,  # HDF5 creation processes
    },
    "OPTIMIZER": {
        "OPTIMIZING_METHOD": "adamW",
        "BASE_LR": 0.001,
        "WEIGHT_DECAY": 0.0001,
        "LR_SCHEDULER": "cosine",
        "WARMUP_EPOCHS": 1.0,
        "ETA_MIN": 0.00001,
    },
    "DATA": {
        "AUG_DEVICE": "gpu",
        "SITE_BALANCE": "sqrt",
        "AUG": ["Scaling", "Rotation", "Translation", "BiasField", "RGamma", "Noise"],
        "AUG_PROBABILITIES": {"Scaling": 0.8, "Rotation": 0.5, "Translation": 0.8,
                              "BiasField": 0.6, "RGamma": 0.3, "Noise": 0.2},
        "AUG_SCALING": {"SCALES": [0.85, 1.15]},
        "AUG_ROTATION": {"DEGREES": 10},
        "AUG_TRANSLATION": {"TRANSLATION": [15.0, 15.0, 0]},
        "AUG_BIASFIELD": {"COEFFICIENTS": [0.3, 0.5], "ORDER": 3},
        "AUG_RGAMMA": {"LOG_GAMMA": [-0.2, 0.2]},
        "AUG_NOISE": {"STD": 0.03},
    },
    "DATA_LOADER": {"NUM_WORKERS": 3, "VAL_NUM_WORKERS": 1, "PREFETCH_FACTOR": 2,
                    "PIN_MEMORY": True, "HDF5_CACHE_MB": 64},
    "NUM_GPUS": 1,
    "RNG_SEED": 42,
}

FROM_CHECKPOINT_DATA = ["PLANE", "CLASS_OPTIONS", "SIZES", "PADDED_SIZE", "PREPROCESSING"]


def set_key(d: dict, dotted: str, value: str) -> None:
    keys = dotted.split(".")
    for k in keys[:-1]:
        d = d.setdefault(k, {})
    d[keys[-1]] = yaml.safe_load(value)


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--from-checkpoint", type=Path, required=True)
    p.add_argument("--contrast", required=True, help="T1w, T2w, T2wExvivo ...")
    p.add_argument("--data-dir", required=True, help="TRAINING_DATA_DIR (images/, labels/)")
    p.add_argument("--output-dir", required=True, help="OUTPUT_DIR for this run")
    p.add_argument("--pretrained", default=None,
                   help="PRETRAINED_MODEL (default: the --from-checkpoint file)")
    p.add_argument("--set", nargs="*", default=[], metavar="KEY=VALUE")
    p.add_argument("--out", type=Path, required=True)
    args = p.parse_args()

    ck = read_checkpoint_file(args.from_checkpoint, map_location="cpu")
    src = yaml.safe_load(ck["config"])
    cfg = {
        "TRAINING_DATA_DIR": str(args.data_dir),
        "OUTPUT_DIR": str(args.output_dir),
        "MODEL": src["MODEL"],
        "DATA": {k: src["DATA"][k] for k in FROM_CHECKPOINT_DATA if k in src["DATA"]},
    }
    cfg["DATA"]["CONTRAST"] = args.contrast
    for top, val in RECIPE.items():
        if isinstance(val, dict):
            cfg.setdefault(top, {}).update(val)
        else:
            cfg[top] = val
    cfg["TRAIN"]["PRETRAINED_MODEL"] = str(args.pretrained or args.from_checkpoint.resolve())
    for item in args.set:
        k, v = item.split("=", 1)
        set_key(cfg, k, v)

    header = (
        f"# Generated by fastsurfer_nn/scripts/make_training_yaml.py\n"
        f"# MODEL and DATA.{{{','.join(FROM_CHECKPOINT_DATA)}}} copied from "
        f"{args.from_checkpoint.name}\n"
        f"# (do not edit those unless you also retrain from scratch); the rest is the recipe.\n"
        f"# Run: src/fastsurfer_nn/scripts/run_training_pipeline.sh --config {args.out}\n"
    )
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(header + yaml.safe_dump(cfg, sort_keys=False, default_flow_style=False))
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
